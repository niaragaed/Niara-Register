// Minimal client for the Niara-Register program on Solana (niara-register-solana),
// v1 records only: reading them. The program no longer accepts new v1 records
// (they stored name/type in plain text); new registrations go through
// lib/register-v2-solana.ts.
//
// v1 semantics, same as RegistroAssinaturas.sol: SHA-256 hash + signer +
// timestamp + name/type, one record per hash, immutable.
//
// No Anchor client in the browser, on purpose: the instruction and the account
// are small enough to encode by hand, and this avoids Node polyfills (Buffer
// etc.) in the Next bundle. The discriminators below come from the IDL
// generated by `anchor build` (target/idl/niara_register_solana.json): if the
// program's signature changes, update here.
import {
  Connection,
  PublicKey,
} from "@solana/web3.js";

/** The program's public address (public information, like the EVM contract's). */
export const SOLANA_PROGRAM_ID = new PublicKey(
  "9RPHqLouFjoUbPdcmA1GyHMeDoWvjZMuCyYFPBWLmTcR",
);

export const SOLANA_CLUSTER = "devnet" as const;

export const SOLANA_RPC =
  process.env.NEXT_PUBLIC_SOLANA_RPC_URL ?? "https://api.devnet.solana.com";

// On-chain PDA seed of the program.
const SIGNATURE_SEED = new TextEncoder().encode("assinatura");
const SIGNATURE_ACCOUNT_DISC = Uint8Array.from([
  68, 120, 123, 196, 84, 89, 85, 188,
]);

export type SolanaRecord = {
  signer: string;
  timestamp: number;
  slot: number;
  documentName: string;
  documentType: string;
};

function hexToBytes(hex: string): Uint8Array {
  const clean = hex.startsWith("0x") ? hex.slice(2) : hex;
  if (!/^[0-9a-fA-F]{64}$/.test(clean)) {
    throw new Error("Invalid SHA-256 hash (expected 64 hex characters).");
  }
  const bytes = new Uint8Array(32);
  for (let i = 0; i < 32; i++) {
    bytes[i] = parseInt(clean.slice(i * 2, i * 2 + 2), 16);
  }
  return bytes;
}

/** PDA ["assinatura", hash]: one address (and therefore one record) per document. */
export function recordAddress(hashHex: string): PublicKey {
  return PublicKey.findProgramAddressSync(
    [SIGNATURE_SEED, hexToBytes(hashHex)],
    SOLANA_PROGRAM_ID,
  )[0];
}

export function solanaConnection(): Connection {
  return new Connection(SOLANA_RPC, "confirmed");
}

/**
 * Reads a hash's record straight from the on-chain account. No wallet needed:
 * anyone can verify a document with just the file in hand.
 */
export async function fetchSolanaRecord(
  connection: Connection,
  hashHex: string,
): Promise<SolanaRecord | null> {
  const account = await connection.getAccountInfo(recordAddress(hashHex));
  if (!account) return null;
  if (!account.owner.equals(SOLANA_PROGRAM_ID)) return null;

  const data = Uint8Array.from(account.data);
  for (let i = 0; i < 8; i++) {
    if (data[i] !== SIGNATURE_ACCOUNT_DISC[i]) return null;
  }

  const view = new DataView(data.buffer, data.byteOffset, data.byteLength);
  const decoder = new TextDecoder();
  let pos = 8;

  const signer = new PublicKey(data.slice(pos, pos + 32)).toBase58();
  pos += 32;
  pos += 32; // hash_documento (we already know which one it is)
  const timestamp = Number(view.getBigInt64(pos, true));
  pos += 8;
  const slot = Number(view.getBigUint64(pos, true));
  pos += 8;

  const readString = () => {
    const length = view.getUint32(pos, true);
    pos += 4;
    const text = decoder.decode(data.slice(pos, pos + length));
    pos += length;
    return text;
  };
  const documentName = readString();
  const documentType = readString();

  return { signer, timestamp, slot, documentName, documentType };
}

export function solanaExplorerLink(
  kind: "tx" | "address",
  value: string,
): string {
  return `https://explorer.solana.com/${kind}/${value}?cluster=${SOLANA_CLUSTER}`;
}
